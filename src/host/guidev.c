/* freecuplw - build helper: the table of mnemonics, pin counts and part
   names for the device dialogs, from the device description files.
   Runs on the build host.  DARKSOFT.
   usage: guidev out.c file.dev ... */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define MAXDESC 1024
#define MAXMN   2048

typedef struct {
    char name[40], parent[40];
    int pins;
    char descr[128];
} Desc;

typedef struct {
    int desc;
    char mn[40], part[128];
} Mn;

static Desc desc[MAXDESC];
static int ndesc;
static Mn mn[MAXMN];
static int nmn;

static void die(const char *m, const char *a)
{
    fprintf(stderr, "guidev: %s %s\n", m, a);
    exit(1);
}

static int pins_of(int d, int depth)
{
    int i;
    if (desc[d].pins || !desc[d].parent[0] || depth > 20) return desc[d].pins;
    for (i = 0; i < ndesc; i++)
        if (!strcmp(desc[i].name, desc[d].parent)) return pins_of(i, depth + 1);
    return 0;
}

/* rest of the line after the first skip words, '|' written as '/' */
static void rest(const char *line, int skip, char *out, size_t n)
{
    const char *p = line;
    size_t k = 0;
    while (skip--) {
        while (*p == ' ' || *p == '\t') p++;
        while (*p && *p != ' ' && *p != '\t') p++;
    }
    while (*p == ' ' || *p == '\t') p++;
    for (; *p && k + 1 < n; p++) out[k++] = (*p == '|') ? '/' : *p;
    while (k && (out[k - 1] == ' ' || out[k - 1] == '\t')) k--;
    out[k] = 0;
}

static void read_file(const char *path)
{
    FILE *f = fopen(path, "r");
    char line[8192], w1[64], w2[64];
    int cur = -1, i;
    if (!f) die("cannot open", path);
    while (fgets(line, sizeof line, f)) {
        char *h = strchr(line, '#');
        size_t l;
        int n;
        if (h) *h = 0;
        l = strlen(line);
        while (l && (line[l - 1] == '\n' || line[l - 1] == '\r')) line[--l] = 0;
        w1[0] = w2[0] = 0;
        n = sscanf(line, "%63s %63s", w1, w2);
        if (n < 1) continue;
        if (!strcmp(w1, "device") && n == 2) {
            if (ndesc == MAXDESC) die("too many descriptions in", path);
            cur = ndesc++;
            memset(&desc[cur], 0, sizeof desc[cur]);
            strncpy(desc[cur].name, w2, sizeof desc[cur].name - 1);
        } else if (cur < 0) {
            continue;
        } else if (!strcmp(w1, "inherit") && n == 2) {
            strncpy(desc[cur].parent, w2, sizeof desc[cur].parent - 1);
        } else if (!strcmp(w1, "pins") && n == 2) {
            desc[cur].pins = atoi(w2);
        } else if (!strcmp(w1, "descr")) {
            rest(line, 1, desc[cur].descr, sizeof desc[cur].descr);
        } else if (!strcmp(w1, "alias") && n == 2) {
            if (nmn == MAXMN) die("too many mnemonics in", path);
            memset(&mn[nmn], 0, sizeof mn[nmn]);
            mn[nmn].desc = cur;
            strncpy(mn[nmn].mn, w2, sizeof mn[nmn].mn - 1);
            nmn++;
        } else if (!strcmp(w1, "partname") && n == 2) {
            for (i = nmn - 1; i >= 0 && mn[i].desc == cur; i--)
                if (!strcmp(mn[i].mn, w2)) break;
            if (i < 0 || mn[i].desc != cur) {
                /* the description itself, which has no alias */
                if (strcmp(desc[cur].name, w2)) die("partname without mnemonic:", w2);
                if (nmn == MAXMN) die("too many mnemonics in", path);
                i = nmn++;
                memset(&mn[i], 0, sizeof mn[i]);
                mn[i].desc = cur;
                strncpy(mn[i].mn, w2, sizeof mn[i].mn - 1);
            }
            rest(line, 2, mn[i].part, sizeof mn[i].part);
        }
    }
    fclose(f);
}

static int cmp(const void *a, const void *b)
{
    return strcmp(((const Mn *)a)->mn, ((const Mn *)b)->mn);
}

int main(int argc, char **argv)
{
    FILE *o;
    int i, j;
    if (argc < 3) {
        fprintf(stderr, "usage: guidev out.c file.dev ...\n");
        return 2;
    }
    for (i = 2; i < argc; i++) read_file(argv[i]);
    /* a description without alias and without partname */
    for (i = 0; i < ndesc; i++) {
        for (j = 0; j < nmn; j++)
            if (mn[j].desc == i) break;
        if (j < nmn) continue;
        if (nmn == MAXMN) die("too many mnemonics", "");
        memset(&mn[nmn], 0, sizeof mn[nmn]);
        mn[nmn].desc = i;
        strcpy(mn[nmn].mn, desc[i].name);
        nmn++;
    }
    for (j = 0; j < nmn; j++)
        if (!mn[j].part[0]) {
            const Desc *d = &desc[mn[j].desc];
            strcpy(mn[j].part, d->descr[0] ? d->descr : d->name);
        }
    for (j = 0; j < nmn; j++) mn[j].desc = pins_of(mn[j].desc, 0);
    qsort(mn, (size_t)nmn, sizeof mn[0], cmp);
    o = fopen(argv[1], "w");
    if (!o) die("cannot write", argv[1]);
    fprintf(o, "/* generated by guidev from the device descriptions */\n");
    fprintf(o, "#include \"gui/core.h\"\n");
    fprintf(o, "const GuiDev gui_devs[] = {\n");
    for (j = 0; j < nmn; j++) {
        const char *p;
        fprintf(o, "    { \"%s\", %d, \"", mn[j].mn, mn[j].desc);
        for (p = mn[j].part; *p; p++) {
            if (*p == '"' || *p == '\\') fputc('\\', o);
            fputc(*p, o);
        }
        fprintf(o, "\" },\n");
    }
    fprintf(o, "};\nconst int gui_ndevs = %d;\n", nmn);
    if (fclose(o)) die("cannot write", argv[1]);
    return 0;
}
