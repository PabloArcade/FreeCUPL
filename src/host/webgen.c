/* freecupl - build helper for freecupl serve.  Runs on the build host.
   DARKSOFT.
   usage: webgen out.c name=file ...   the files as byte arrays web_<name>
          webgen -kw out.js            the reserved words of the editor
                                       colouring for the page (links
                                       src/gui/core.c) */
#include "gui/core.h"
#include <stdio.h>
#include <string.h>

int main(int argc, char **argv)
{
    FILE *o;
    int i;
    if (argc == 3 && !strcmp(argv[1], "-kw")) {
        o = fopen(argv[2], "w");
        if (!o) { perror(argv[2]); return 1; }
        fprintf(o, "/* generated from the table of src/gui/core.c */\n\"use strict\";\n"
                   "var FC_KEYWORDS = [");
        for (i = 0; i < gui_nkeywords; i++)
            fprintf(o, "%s\n  \"%s\"", i ? "," : "", gui_keywords[i]);
        fprintf(o, "\n];\nvar FC_CLASS = { plain: %d, comment: %d, keyword: %d, number: %d };\n",
                GA_PLAIN, GA_COMMENT, GA_KEYWORD, GA_NUMBER);
        return fclose(o) ? 1 : 0;
    }
    if (argc < 3) {
        fprintf(stderr, "usage: webgen out.c name=file ...\n       webgen -kw out.js\n");
        return 2;
    }
    o = fopen(argv[1], "w");
    if (!o) { perror(argv[1]); return 1; }
    fprintf(o, "/* generated by webgen - do not edit */\n");
    for (i = 2; i < argc; i++) {
        char name[64];
        const char *eq = strchr(argv[i], '=');
        FILE *f;
        unsigned long n = 0;
        int c;
        if (!eq || eq == argv[i] || (size_t)(eq - argv[i]) >= sizeof name) {
            fprintf(stderr, "webgen: bad argument %s\n", argv[i]);
            return 2;
        }
        memcpy(name, argv[i], (size_t)(eq - argv[i]));
        name[eq - argv[i]] = 0;
        f = fopen(eq + 1, "rb");
        if (!f) { perror(eq + 1); return 1; }
        fprintf(o, "const unsigned char web_%s[] = {", name);
        while ((c = getc(f)) != EOF) {
            /* text files are stored with LF line ends */
            if (c == '\r' && strcmp(name, "favicon_ico")) continue;
            fprintf(o, "%s%d,", n % 20 ? "" : "\n", c);
            n++;
        }
        fclose(f);
        fprintf(o, "\n0 };\nconst unsigned web_%s_len = %luu;\n", name, n);
    }
    return fclose(o) ? 1 : 0;
}
