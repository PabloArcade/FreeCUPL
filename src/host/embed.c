/* freecupl - build helper: turns device description files into a C source
   holding them as string literals.  Runs on the build host.  DARKSOFT.
   usage: embed out.c file.dev ... */
#include <stdio.h>
#include <string.h>

static const char *base(const char *p)
{
    const char *b = p, *s;
    for (s = p; *s; s++) if (*s == '/' || *s == '\\') b = s + 1;
    return b;
}

/* one block per device, split into string literals short enough for any
   C99 compiler; the loader joins them */
#define CHUNK 3500

static FILE *o;
static int nchunk;        /* chunks of the open block */
static size_t chunklen;
static int open_;
static int nblk;

static void close_chunk(void)
{
    fprintf(o, "\";\n");
    open_ = 0;
}

static void open_chunk(void)
{
    fprintf(o, "static const char dev_%d_%d[] =\n\"", nblk - 1, nchunk++);
    chunklen = 0;
    open_ = 1;
}

static void close_block(void)
{
    int k;
    if (open_) close_chunk();
    fprintf(o, "static const char *const dev_%d[] = {", nblk - 1);
    for (k = 0; k < nchunk; k++) fprintf(o, " dev_%d_%d,", nblk - 1, k);
    fprintf(o, " NULL };\n");
}

int main(int argc, char **argv)
{
    int i, k, inblock = 0;
    static char names[4096][64];
    if (argc < 2) { fprintf(stderr, "usage: embed out.c files...\n"); return 2; }
    o = fopen(argv[1], "w");
    if (!o) { perror(argv[1]); return 1; }
    fprintf(o, "/* generated by embed from the devices directory - do not edit */\n");
    fprintf(o, "#include <stddef.h>\n");
    for (i = 2; i < argc; i++) {
        FILE *f = fopen(argv[i], "rb");
        char line[4096];
        int blk = 0;
        if (!f) { perror(argv[i]); return 1; }
        while (fgets(line, sizeof line, f)) {
            const char *s = line;
            size_t len = strlen(line);
            while (*s == ' ' || *s == '\t') s++;
            if (!strncmp(s, "device", 6) && (s[6] == ' ' || s[6] == '\t') && inblock) {
                close_block();
                inblock = 0;
            }
            if (!inblock) {
                if (nblk == 4096) { fprintf(stderr, "embed: too many device blocks\n"); return 1; }
                sprintf(names[nblk], "%.40s#%d", base(argv[i]), ++blk);
                nblk++;
                nchunk = 0;
                inblock = 1;
                open_chunk();
            } else if (chunklen + len > CHUNK) {
                close_chunk();
                open_chunk();
            }
            for (k = 0; k < (int)len; k++) {
                int c = (unsigned char)line[k];
                if (c == '\r') continue;
                chunklen++;
                if (c == '\n') { fprintf(o, "\\n\"\n\""); continue; }
                if (c == '"' || c == '\\') fputc('\\', o);
                if (c < 32 || c > 126) { fprintf(o, "\\%03o", c); continue; }
                fputc(c, o);
            }
        }
        if (inblock) { close_block(); inblock = 0; }
        fclose(f);
    }
    fprintf(o, "const char *const *const freecupl_builtin_devices[] = {");
    for (i = 0; i < nblk; i++) fprintf(o, " dev_%d,", i);
    fprintf(o, " NULL };\nconst char *const freecupl_builtin_device_names[] = {");
    for (i = 0; i < nblk; i++) fprintf(o, " \"%s\",", names[i]);
    fprintf(o, " NULL };\n");
    return fclose(o) ? 1 : 0;
}
